const WAVEFORM_ENUM: Record<SfxParams['waveform'], string> = {
  square: 'Square',
  sawtooth: 'Sawtooth',
  sine: 'Sine',
  noise: 'Noise',
};

const TERRAIN_ENUM: Record<SfxParams['footstepTerrain'], string> = {
  snow: 'Snow',
  grass: 'Grass',
  dirt: 'Dirt',
  gravel: 'Gravel',
  mud: 'Mud',
  wood: 'Wood',
  metal: 'Metal',
  water: 'Water',
};

function num(value: number): string {
  if (value === 0) return '0';
  return String(value);
}

function paramsLiteral(params: SfxParams): string {
  const lines = [
    `new SfxParams {`,
    `      engine = SfxEngine.${params.engine === 'sfxr' ? 'Sfxr' : 'Footsteppr'},`,
    `      waveform = SfxWaveform.${WAVEFORM_ENUM[params.waveform]},`,
    `      footstepTerrain = SfxFootstepTerrain.${TERRAIN_ENUM[params.footstepTerrain]},`,
  ];
  for (const [key, value] of Object.entries(params)) {
    if (key === 'engine' || key === 'waveform' || key === 'footstepTerrain') continue;
    lines.push(`      ${key} = ${num(value as number)},`);
  }
  lines.push(`    }`);
  return lines.join('\n');
}

const HEADER = `// <auto-generated>
// Generated by tools/generate-golden.test.ts from the web engine. Do not edit by hand.
using AFCT.SfxLab;
`;

describe('golden fixtures', () => {
  it('writes preset and audio fixtures for the Unity port', () => {
    mkdirSync(OUT, { recursive: true });

    const seeds = [1234, 42, 987654321];
    const presetCases = SFX_PRESET_ORDER.flatMap((preset) =>
      seeds.map((seed) => ({ preset, seed, params: createSfxPreset(preset, DEFAULT_SFX_PARAMS, { seed }) })),
    );

    writeFileSync(
      join(OUT, 'PresetFixtures.g.cs'),
      `${HEADER}
namespace AFCT.SfxLab.Tests
{
    public static class PresetFixtures
    {
        public sealed class Case
        {
            public string Preset;
            public int Seed;
            public SfxParams Params;
        }

        public static readonly Case[] All = new Case[]
        {
${presetCases
  .map(
    (c) => `            new Case { Preset = "${PRESET_ENUM[c.preset]}", Seed = ${c.seed}, Params = ${paramsLiteral(c.params)} },`,
  )
  .join('\n')}
        };
    }
}
`,
    );

    const audioCases: Array<{ id: string; sampleRate: number; seed: number; params: SfxParams }> = [
      { id: 'click', sampleRate: 44100, seed: 1234, params: createSfxPreset('click', DEFAULT_SFX_PARAMS, { seed: 1234 }) },
      { id: 'blip-select', sampleRate: 22050, seed: 1234, params: createSfxPreset('blipSelect', DEFAULT_SFX_PARAMS, { seed: 1234 }) },
      { id: 'error-buzz', sampleRate: 22050, seed: 1234, params: createSfxPreset('errorBuzz', DEFAULT_SFX_PARAMS, { seed: 1234 }) },
      { id: 'explosion', sampleRate: 22050, seed: 1234, params: createSfxPreset('explosion', DEFAULT_SFX_PARAMS, { seed: 1234 }) },
      { id: 'whoosh', sampleRate: 22050, seed: 1234, params: createSfxPreset('whoosh', DEFAULT_SFX_PARAMS, { seed: 1234 }) },
      { id: 'impact', sampleRate: 22050, seed: 1234, params: createSfxPreset('impact', DEFAULT_SFX_PARAMS, { seed: 1234 }) },
      { id: 'glitch', sampleRate: 22050, seed: 1234, params: createSfxPreset('glitch', DEFAULT_SFX_PARAMS, { seed: 1234 }) },
      { id: 'synth', sampleRate: 44100, seed: 1234, params: createSfxPreset('synth', DEFAULT_SFX_PARAMS, { seed: 1234 }) },
      { id: 'footstep-snow', sampleRate: 22050, seed: 1234, params: createSfxPreset('footstepSnow', DEFAULT_SFX_PARAMS, { seed: 1234 }) },
      { id: 'footstep-metal', sampleRate: 44100, seed: 1234, params: createSfxPreset('footstepMetal', DEFAULT_SFX_PARAMS, { seed: 1234 }) },
      { id: 'footstep-water', sampleRate: 22050, seed: 1234, params: createSfxPreset('footstepWater', DEFAULT_SFX_PARAMS, { seed: 1234 }) },
      { id: 'default-params', sampleRate: 48000, seed: 1234, params: { ...DEFAULT_SFX_PARAMS } },
    ];

    for (const audio of audioCases) {
      const rendered = renderSfx(audio.params, { sampleRate: audio.sampleRate, bitDepth: 16, seed: audio.seed });
      const bytes = Buffer.from(rendered.samples.buffer, rendered.samples.byteOffset, rendered.samples.byteLength);
      writeFileSync(join(OUT, `${audio.id}.f32`), bytes);
    }

    writeFileSync(
      join(OUT, 'Fixtures.g.cs'),
      `${HEADER}
namespace AFCT.SfxLab.Tests
{
    public static class AudioFixtures
    {
        public sealed class Case
        {
            public string Id;
            public int SampleRate;
            public int BitDepth;
            public int Seed;
            public SfxParams Params;
        }

        public static readonly Case[] All = new Case[]
        {
${audioCases
  .map(
    (c) =>
      `            new Case { Id = "${c.id}", SampleRate = ${c.sampleRate}, BitDepth = 16, Seed = ${c.seed}, Params = ${paramsLiteral(c.params)} },`,
  )
  .join('\n')}
        };
    }
}
`,
    );

    expect(presetCases.length).toBe(84);
    expect(audioCases.length).toBe(12);
  });
});
